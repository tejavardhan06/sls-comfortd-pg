// Run: node scripts/optimize-media.js <path-to-ffmpeg>
// Videos are copied byte for byte; only photos and preview thumbnails are optimized.
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const root = path.resolve(__dirname, '..');
const ffmpeg = process.argv[2] || 'ffmpeg';
fs.mkdirSync(path.join(root, 'media'), { recursive: true });
const assets = {};
function run(args) {
  const result = spawnSync(ffmpeg, ['-hide_banner', '-loglevel', 'error', '-y', ...args], { cwd: root, stdio: 'inherit' });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error('Media conversion failed');
}
for (const file of fs.readdirSync(root)) {
  const stem = path.parse(file).name;
  if (/\.mp4$/i.test(file)) {
    const poster = `media/${stem}-poster.webp`;
    const video = `media/${stem}.mp4`;
    run(['-i', file, '-frames:v', '1', '-vf', 'scale=960:960:force_original_aspect_ratio=decrease', '-quality', '78', poster]);
    fs.copyFileSync(path.join(root, file), path.join(root, video));
    assets[file] = { src: video, poster };
  } else if (/\.jpe?g$/i.test(file)) {
    const image = `media/${stem}.webp`;
    run(['-i', file, '-frames:v', '1', '-vf', 'scale=1280:1280:force_original_aspect_ratio=decrease', '-quality', '80', image]);
    assets[file] = { src: image };
  }
}
fs.writeFileSync(path.join(root, 'js/media-assets.js'), `/* Generated by scripts/optimize-media.js */\nconst MEDIA_ASSETS = ${JSON.stringify(assets, null, 2)};\n`);
console.log(`Prepared ${Object.keys(assets).length} assets with original-quality videos.`);
